#!/usr/bin/env python3
"""Generate genuine Falcon-512 signatures that drive the squeeze into its rare paths.

The hash-to-point squeezes 68 16-bit words per SHAKE-256 block and keeps those below 5q.
Signatures that need nine blocks normally finish from the first 16 words of block 9
(lanes 0..3). This script grinds salts so that the stream after eight blocks is in a chosen
state, then signs over it with a fresh key (tprest/falcon.py), so every vector is a valid
signature the reference verifier accepts:

  tail_k    k coefficients missing after 8 blocks and all k found in block 9's first 16 words
  fb_miss   17..40 missing after 8 blocks (block 9 needs words past lane 3)
  fb_head   1..16 missing, but block 9's first 16 words hold fewer than that many accepts
  eight_k   finishes within block 8 with k words of block 8 unused

Outputs crates/falcon_512/tests/edge_fixtures.cairo + bench_edge.cairo (one test per vector,
asserting the reference verdict) and pythonref/fixtures/edge.json.

Usage: pythonref/.venv/bin/python pythonref/gen_edge_fixtures.py [--per-kind N]
"""

import argparse
import hashlib
import json
import os
import secrets
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_mix_fixtures as gm  # noqa: E402  (sets up vendor paths)

ref = gm.ref
WORDS = ref.WORDS_PER_BLOCK


def stream_state(message: int, salt: bytes):
    """(accepted after 8 blocks, accepted in block 9's first 16 words, words used in total)."""
    words = hashlib.shake_256(salt + message.to_bytes(32, "little")).digest(WORDS * 2 * 10)
    acc = 0
    acc8 = None
    head = 0
    used = 0
    for i in range(WORDS * 10):
        w = (words[2 * i] << 8) | words[2 * i + 1]
        if i == WORDS * 8:
            acc8 = acc
        if WORDS * 8 <= i < WORDS * 8 + 16 and w < ref.ACCEPT_BELOW:
            head += 1
        if acc < ref.N and w < ref.ACCEPT_BELOW:
            acc += 1
            used = i + 1
    return acc8, head, used


def grind(pred, limit=2_000_000):
    message = secrets.randbelow(ref.FELT_PRIME)
    for _ in range(limit):
        salt = os.urandom(ref.SALT_BYTES)
        st = stream_state(message, salt)
        if pred(*st):
            return message, salt, st
    raise SystemExit("grind limit reached")


def sign(scheme, message: int, salt: bytes) -> dict:
    sk, _ = scheme.keygen()
    f, g, _F, _G, B0_fft, T_fft = sk
    h = gm.div_zq(g, f)
    point, _ = ref.hash_to_point(message, salt)
    while True:
        s = scheme.__sample_preimage__(B0_fft, T_fft, point)
        if sum(c * c for c in s[0]) + sum(c * c for c in s[1]) <= ref.SIG_BOUND:
            break
    s1 = [c % ref.Q for c in s[1]]
    hint = gm.mul_zq(s1, h)
    pk = gm.pack_512(ref.ntt(h))
    sig = (gm.pack_512(s1) + [int.from_bytes(salt[:20], "little"),
                              int.from_bytes(salt[20:], "little")] + gm.pack_512(hint))
    v = ref.verify(message, pk, sig)
    assert v.valid, v
    return {"message": message, "public_key": pk, "signature": sig, "valid": True}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--per-kind", type=int, default=3)
    args = ap.parse_args()
    scheme = gm.fpy.Falcon(512)
    kinds = []
    for k in (1, 15, 16):
        kinds.append((f"tail_{k}", lambda a8, hd, u, k=k: a8 == 512 - k and hd >= k))
    kinds.append(("fb_miss", lambda a8, hd, u: a8 is not None and 472 <= a8 <= 495))
    kinds.append(("fb_head", lambda a8, hd, u: a8 is not None and 496 <= a8 < 512 and hd < 512 - a8))
    for k in (0, 1, 8):
        kinds.append((f"eight_{k}", lambda a8, hd, u, k=k: a8 is not None and a8 >= 512 and u == WORDS * 8 - k))
    vectors = []
    for name, pred in kinds:
        for j in range(args.per_kind):
            message, salt, st = grind(pred)
            fx = sign(scheme, message, salt)
            fx["kind"] = name
            fx["stream"] = st
            vectors.append(fx)
            print(f"{name}[{j}]: acc8={st[0]} head={st[1]} used={st[2]}", flush=True)

    out = HERE / "fixtures/edge.json"
    out.write_text(json.dumps([{**v, "message": hex(v["message"]),
                                "public_key": [hex(x) for x in v["public_key"]],
                                "signature": [hex(x) for x in v["signature"]]} for v in vectors],
                              indent=1) + "\n")
    write_cairo("edge", vectors)


def write_cairo(name: str, vectors: list) -> None:
    """Fixture module + one test per vector asserting the reference verdict."""
    repo = HERE.parent
    lines = [f"//! GENERATED by `pythonref/` — do not edit by hand. {len(vectors)} vectors.\n"]
    arms = []
    for i, v in enumerate(vectors):
        pk = ",".join(hex(x) for x in v["public_key"])
        sig = ",".join(hex(x) for x in v["signature"])
        lines.append(f"fn v{i}() -> (felt252, Array<felt252>, Array<felt252>) {{\n"
                     f"    ({hex(v['message'])}, array![{pk}], array![{sig}])\n}}\n")
        arms.append(f"        {i} => v{i}(),")
    lines.append("pub fn vector(i: u32) -> (felt252, Array<felt252>, Array<felt252>) {\n"
                 "    match i {\n" + "\n".join(arms) + "\n        _ => panic!(\"no such vector\"),\n    }\n}\n")
    (repo / f"crates/falcon_512/tests/{name}_fixtures.cairo").write_text("\n".join(lines))
    tests = [f"//! GENERATED by `pythonref/` — do not edit by hand.\n",
             "use pqbench_falcon_512::Falcon512ShakeVerifier;\n"
             "use pqbench_interface::PqSignatureVerifier;\n"
             f"use crate::{name}_fixtures::vector;\n"]
    for i, v in enumerate(vectors):
        exp = "true" if v["valid"] else "false"
        tests.append(f"/// {v.get('kind', '')} {v.get('stream', '')}\n#[test]\nfn {name}_{i:03}() {{\n"
                     f"    let (m, pk, sig) = vector({i});\n"
                     f"    assert!(Falcon512ShakeVerifier::verify(m, pk.span(), sig.span()) == {exp});\n}}\n")
    (repo / f"crates/falcon_512/tests/bench_{name}.cairo").write_text("\n".join(tests))
    print(f"wrote {name}: {len(vectors)} vectors")


if __name__ == "__main__":
    main()
