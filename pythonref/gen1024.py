#!/usr/bin/env python3
"""Break-track vectors for the Falcon-1024 season, judged by its reference verifier.

Suites (each writes crates/falcon_1024/tests/<name>_fixtures.cairo + bench_<name>.cairo with
one test per vector asserting the reference verdict, plus pythonref/fixtures/<name>1024.json):

  edge   genuine signatures driving the squeeze into its rare states (16-block finishes at
         and near block ends; k coefficients missing after 16 blocks found in block 17's first
         16 words; 17+ missing; block 17's head short of accepts) and over edge-valued
         messages and salts
  norm   signatures at the norm bound's edge: valid ones within 1% below it and invalid ones
         up to 2% over it, made by walking a genuine signature along the key's own lattice
         (s0 + g*x, s1 - f*x keeps s0 + s1*h = c, so the hint stays consistent)
  zk     genuine keys whose packed public key has chosen zero halves or slots, including the
         last slot's nine-low/seven-high halves (a short LLL/Babai correction to g)
  fuzz   mutations of genuine signatures (every felt to edge values and non-canonical
         re-encodings, salt edges, lengths, swapped felts, another key, s1 re-hinted to match)
         written to crates/falcon_1024/tests/data/fuzz.txt (gitignored) with a chunked harness

Keys are cached in pythonref/fixtures/keys1024.json (falcon.py keygen at n = 1024 is slow).
Usage: pythonref/.venv/bin/python pythonref/gen1024.py edge|norm|zk|fuzz [chunk]
"""
