#!/usr/bin/env python3
"""Mutation fuzz vectors for the Break track, judged by the challenge's reference verifier.

Bases are genuine signatures (fixtures/mix.json, fixtures/edge.json). Each felt of the
input (message, 29 key felts, 60 signature felts) is replaced by edge values — 0, 1, p - 1,
2^128 +- 1, +-1, non-canonical re-encodings of the same digits, salt-range edges — and the
lengths are cut and padded. Every vector carries the reference verdict
(`falcon512.verify(...).valid`); vectors with identical inputs are dropped.

Writes crates/falcon_512/tests/data/fuzz.txt (one felt per line: count, then per vector
`expected, message, len(pk), pk..., len(sig), sig...`) and crates/falcon_512/tests/
bench_fuzz.cairo (chunked tests that verify each vector, print `idx got expected gas`, and
fail on any verdict mismatch). Also pythonref/fixtures/fuzz.json for attack vectors.

Usage: pythonref/.venv/bin/python pythonref/gen_fuzz.py [--bases N] [--chunk K]
"""

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
import sys
sys.path.insert(0, str(HERE / "vendor"))
import falcon512 as ref  # noqa: E402

P = ref.FELT_PRIME
Q = ref.Q
Q9 = Q ** 9
Q8 = Q ** 8
T128 = 1 << 128


def load(name):
    out = []
    for v in json.loads((HERE / "fixtures" / name).read_text()):
        out.append((int(v["message"], 16), [int(x, 16) for x in v["public_key"]],
                    [int(x, 16) for x in v["signature"]]))
    return out


def slot_variants(x: int, last: bool) -> list[int]:
    lo, hi = x % T128, x // T128
    vs = [x + 1, x - 1, x + T128, x - T128, lo, hi * T128]
    if last:
        vs += [x + Q8, Q8 - 1, Q8, x + T128 * 1]
    else:
        vs += [lo + Q9 + hi * T128, Q9 - 1 + hi * T128, Q9 + hi * T128,
               lo + Q9 * T128, lo + (Q9 - 1) * T128, lo + (hi + Q9) * T128]
    return vs


def mutations(msg, pk, sig):
    base = [msg] + pk + sig
    yield "base", msg, pk, sig
    for i, x in enumerate(base):
        if i == 0:
            vals = [0, 1, P - 1, x + 1, x - 1, T128, T128 - 1, 1 << 251]
            kind = "msg"
        elif 1 <= i <= 29:
            vals = [0, 1, P - 1, T128 - 1, T128] + slot_variants(x, i == 29)
            kind = f"pk{i - 1}"
        else:
            j = i - 30
            if j in (29, 30):
                vals = [0, 1, P - 1, (1 << 160) - 1, 1 << 160, x + (1 << 160), x + 1, x - 1]
                kind = f"salt{j - 29}"
            else:
                vals = [0, 1, P - 1, T128 - 1, T128] + slot_variants(x, j in (28, 59))
                kind = f"s1_{j}" if j < 29 else f"t{j - 31}"
        for v in vals:
            v %= P
            if v == x:
                continue
            m = base[:i] + [v] + base[i + 1:]
            yield kind, m[0], m[1:30], m[30:]
    yield "pk_short", msg, pk[:-1], sig
    yield "pk_long", msg, pk + [0], sig
    yield "sig_short", msg, pk, sig[:-1]
    yield "sig_long", msg, pk, sig + [0]
    yield "sig_direct", msg, pk, sig[:31]
    yield "swap_s1_t", msg, pk, sig[31:60] + sig[29:31] + sig[0:29]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bases", type=int, default=4)
    ap.add_argument("--chunk", type=int, default=6)
    args = ap.parse_args()
    bases = load("mix.json")[:2] + load("edge.json")[::6][: max(0, args.bases - 2)]
    seen = set()
    vecs = []
    for b, (msg, pk, sig) in enumerate(bases):
        for kind, m, k, s in mutations(msg, pk, sig):
            key = (m, tuple(k), tuple(s))
            if key in seen:
                continue
            seen.add(key)
            v = ref.verify(m, k, s)
            vecs.append({"base": b, "kind": kind, "valid": v.valid, "reason": v.reason,
                         "message": m, "public_key": k, "signature": s})
    flat = [len(vecs)]
    for v in vecs:
        flat += [1 if v["valid"] else 0, v["message"], len(v["public_key"]), *v["public_key"],
                 len(v["signature"]), *v["signature"]]
    data = REPO / "crates/falcon_512/tests/data"
    data.mkdir(parents=True, exist_ok=True)
    (data / "fuzz.txt").write_text("\n".join(str(x) for x in flat) + "\n")
    (HERE / "fixtures/fuzz.json").write_text(json.dumps(
        [{"base": v["base"], "kind": v["kind"], "valid": v["valid"], "reason": v["reason"],
          "message": hex(v["message"]), "public_key": [hex(x) for x in v["public_key"]],
          "signature": [hex(x) for x in v["signature"]]} for v in vecs]) + "\n")
    n = len(vecs)
    chunks = (n + args.chunk - 1) // args.chunk
    body = [
        "//! GENERATED by `pythonref/gen_fuzz.py` — do not edit by hand.\n//!\n"
        "//! Mutation vectors judged by the falcon.provably.fast reference verifier, read from\n"
        "//! tests/data/fuzz.txt. Each test runs one chunk, prints `FUZZ idx got expected gas`\n"
        "//! per vector, and fails if any verdict differs from the reference.\n",
        "use core::testing::get_available_gas;\n"
        "use pqbench_falcon_512::Falcon512ShakeVerifier;\n"
        "use pqbench_interface::PqSignatureVerifier;\n"
        "use snforge_std::fs::{FileTrait, read_txt};\n",
        f"const CHUNK: u32 = {args.chunk};\n",
        """fn run_chunk(c: u32) {
    let data = read_txt(@FileTrait::new("tests/data/fuzz.txt"));
    let mut d = data.span();
    let n: u32 = (*d.pop_front().unwrap()).try_into().unwrap();
    let mut i: u32 = 0;
    let mut bad: u32 = 0;
    while i < n {
        let expected = *d.pop_front().unwrap() == 1;
        let m = *d.pop_front().unwrap();
        let kl: u32 = (*d.pop_front().unwrap()).try_into().unwrap();
        let pk = d.slice(0, kl);
        d = d.slice(kl, d.len() - kl);
        let sl: u32 = (*d.pop_front().unwrap()).try_into().unwrap();
        let sig = d.slice(0, sl);
        d = d.slice(sl, d.len() - sl);
        if i / CHUNK == c {
            let g0 = get_available_gas();
            let got = Falcon512ShakeVerifier::verify(m, pk, sig);
            let used: felt252 = g0.into() - get_available_gas().into();
            println!("FUZZ {} {} {} {}", i, got, expected, used);
            if got != expected {
                bad += 1;
            }
        }
        i += 1;
    }
    assert!(bad == 0, "verdict mismatch");
}
""",
    ]
    for c in range(chunks):
        body.append(f"#[test]\nfn fuzz_{c:04}() {{\n    run_chunk({c});\n}}\n")
    (REPO / "crates/falcon_512/tests/bench_fuzz.cairo").write_text("\n".join(body))
    acc = sum(v["valid"] for v in vecs)
    print(f"{n} vectors ({acc} valid) in {chunks} chunks")


if __name__ == "__main__":
    main()
