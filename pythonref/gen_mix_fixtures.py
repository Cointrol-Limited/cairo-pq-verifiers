#!/usr/bin/env python3
"""Generate a scorer-shaped set of Falcon-512 SHAKE-256 fixtures.

The falcon.provably.fast scorer averages gas over 27 held-out signatures: 11 whose
hash-to-point squeezes eight SHAKE-256 blocks and 16 that squeeze nine. This script builds
a local set with the same mix: every signature gets a fresh keypair (tprest/falcon.py
NTRU keygen) and a fresh random message, and salts are drawn until the hash-to-point needs
the target number of blocks. Each fixture is accepted by the challenge's reference
verifier before it is written.

Outputs:
  crates/falcon_512/tests/mix_fixtures.cairo   fixture functions (outside the patch)
  crates/falcon_512/tests/bench_mix.cairo      paired mix_verify_NN / mix_base_NN tests
  pythonref/fixtures/mix.json                  the same inputs as JSON (attack-vector shape)

Usage (after pythonref/fetch.sh):
  pythonref/.venv/bin/python pythonref/gen_mix_fixtures.py [--eight 11] [--nine 16]
"""

import argparse
import json
import os
import secrets
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
VENDOR = HERE / "vendor"
sys.path.insert(0, str(VENDOR / "falcon.py"))
sys.path.insert(0, str(VENDOR))
sys.path.insert(0, str(REPO / "scripts"))

import falcon as fpy  # noqa: E402
from ntt import div_zq, mul_zq  # noqa: E402

import falcon512 as ref  # noqa: E402
from gen_falcon_fixture import pack_512, unpack_512  # noqa: E402

OUT_CAIRO = REPO / "crates/falcon_512/tests/mix_fixtures.cairo"
OUT_BENCH = REPO / "crates/falcon_512/tests/bench_mix.cairo"
OUT_JSON = HERE / "fixtures/mix.json"


def make_fixture(scheme, target_blocks: int) -> dict:
    """One fresh key, message and signature whose hash-to-point uses `target_blocks`."""
    sk, _ = scheme.keygen()
    f, g, _F, _G, B0_fft, T_fft = sk
    h = div_zq(g, f)
    h_ntt = ref.ntt(h)

    message = secrets.randbelow(ref.FELT_PRIME)
    while True:
        salt = os.urandom(ref.SALT_BYTES)
        point, blocks = ref.hash_to_point(message, salt)
        if blocks == target_blocks:
            break
    assert point == scheme.__hash_to_point__(message.to_bytes(32, "little"), salt)

    while True:
        s = scheme.__sample_preimage__(B0_fft, T_fft, point)
        norm = sum(c * c for c in s[0]) + sum(c * c for c in s[1])
        if norm <= ref.SIG_BOUND:
            break

    s1 = [c % ref.Q for c in s[1]]
    hint = mul_zq(s1, h)
    pk = pack_512(h_ntt)
    sig = (pack_512(s1)
           + [int.from_bytes(salt[:20], "little"), int.from_bytes(salt[20:], "little")]
           + pack_512(hint))
    assert unpack_512(pk) == h_ntt

    verdict = ref.verify(message, pk, sig)
    assert verdict.valid and verdict.blocks == target_blocks and verdict.norm == norm, verdict
    return {"message": message, "public_key": pk, "signature": sig,
            "blocks": blocks, "norm": norm}


def felt_lines(felts: list[int]) -> str:
    return "\n".join(f"        {hex(v)}," for v in felts)


def write_cairo(fixtures: list[dict]) -> None:
    parts = [
        "//! GENERATED by `pythonref/gen_mix_fixtures.py` — do not edit by hand.\n"
        "//!\n"
        "//! Falcon-512 SHAKE-256 fixtures in the scorer's 8:9-block mix: fresh keypair,\n"
        "//! random message and genuine signature per entry, each accepted by the\n"
        "//! falcon.provably.fast reference verifier. `fixture(i)` returns\n"
        "//! (message, public key, signature).\n",
        f"pub const COUNT: u32 = {len(fixtures)};\n",
    ]
    arms = []
    for i, fx in enumerate(fixtures):
        parts.append(
            f"/// Fixture {i}: {fx['blocks']} SHAKE-256 blocks, squared norm {fx['norm']}.\n"
            f"fn fixture_{i:02}() -> (felt252, Array<felt252>, Array<felt252>) {{\n"
            f"    let pk = array![\n{felt_lines(fx['public_key'])}\n    ];\n"
            f"    let sig = array![\n{felt_lines(fx['signature'])}\n    ];\n"
            f"    ({hex(fx['message'])}, pk, sig)\n}}\n"
        )
        arms.append(f"        {i} => fixture_{i:02}(),")
    parts.append(
        "/// The `i`-th fixture as (message, public key, signature).\n"
        "pub fn fixture(i: u32) -> (felt252, Array<felt252>, Array<felt252>) {\n"
        "    match i {\n" + "\n".join(arms) + "\n        _ => panic!(\"no such fixture\"),\n"
        "    }\n}\n"
    )
    OUT_CAIRO.write_text("\n".join(parts))

    tests = [
        "//! GENERATED by `pythonref/gen_mix_fixtures.py` — do not edit by hand.\n"
        "//!\n"
        "//! Paired gas scenarios over the scorer-shaped fixture mix: `mix_verify_NN` builds\n"
        "//! fixture NN and verifies it, `mix_base_NN` builds the same inputs without\n"
        "//! verifying. `pythonref/mix_gas.py` reports the per-fixture differences and means.\n",
        "use pqbench_falcon_512::Falcon512ShakeVerifier;\n"
        "use pqbench_interface::PqSignatureVerifier;\n"
        "use crate::mix_fixtures::fixture;\n",
    ]
    for i, fx in enumerate(fixtures):
        tests.append(
            f"#[test]\nfn mix_verify_{i:02}() {{\n"
            f"    let (m, pk, sig) = fixture({i});\n"
            f"    assert!(Falcon512ShakeVerifier::verify(m, pk.span(), sig.span()));\n}}\n\n"
            f"#[test]\nfn mix_base_{i:02}() {{\n"
            f"    let (_m, pk, sig) = fixture({i});\n"
            f"    assert!(pk.len() == 29 && sig.len() == 60);\n}}\n"
        )
    OUT_BENCH.write_text("\n".join(tests))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--eight", type=int, default=11, help="8-block fixtures (default 11)")
    parser.add_argument("--nine", type=int, default=16, help="9-block fixtures (default 16)")
    args = parser.parse_args()

    scheme = fpy.Falcon(512)
    assert scheme.param.sig_bound == ref.SIG_BOUND
    targets = [8] * args.eight + [9] * args.nine
    fixtures = []
    for i, target in enumerate(targets):
        fixtures.append(make_fixture(scheme, target))
        print(f"fixture {i:02}: {target} blocks, norm {fixtures[-1]['norm']}", flush=True)

    OUT_JSON.parent.mkdir(exist_ok=True)
    OUT_JSON.write_text(json.dumps(
        [{"message": hex(fx["message"]),
          "public_key": [hex(v) for v in fx["public_key"]],
          "signature": [hex(v) for v in fx["signature"]],
          "blocks": fx["blocks"], "norm": fx["norm"]} for fx in fixtures], indent=1) + "\n")
    write_cairo(fixtures)
    print(f"wrote {OUT_CAIRO.relative_to(REPO)}, {OUT_BENCH.relative_to(REPO)}, "
          f"{OUT_JSON.relative_to(REPO)}")


if __name__ == "__main__":
    main()
